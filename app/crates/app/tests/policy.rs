//! the app's policy files against what the plan's System design states: the content
//! security policy, the two capabilities and the commands each may call, the permission
//! files Tauri generates, and the window's size.
#![allow(
    clippy::unwrap_used,
    clippy::expect_used,
    clippy::panic,
    clippy::indexing_slicing
)]

use std::collections::BTreeSet;
use std::path::PathBuf;

use serde_json::Value;

/// the plan's content security policy, in full.
const CSP: &str = "default-src 'none'; script-src 'self'; style-src 'self'; font-src 'self'; img-src 'self'; connect-src ipc: http://ipc.localhost; object-src 'none'; base-uri 'none'; form-action 'none'; frame-src 'none'; frame-ancestors 'none'";

const MAIN_WINDOW_COMMANDS: [&str; 10] = [
    "read_view",
    "start_all",
    "stop_all",
    "build",
    "stop_build",
    "try_again",
    "set_token",
    "remove_token",
    "hide_window",
    "open_job",
];

const CONFIRMATION_COMMANDS: [&str; 2] = ["read_confirmation", "answer_confirmation"];

fn app_file(relative: &str) -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR")).join(relative)
}

fn json(relative: &str) -> Value {
    let text = std::fs::read_to_string(app_file(relative)).unwrap();
    serde_json::from_str(&text).unwrap()
}

fn permission(command: &str) -> String {
    format!("allow-{}", command.replace('_', "-"))
}

fn strings(value: &Value) -> BTreeSet<String> {
    value
        .as_array()
        .unwrap()
        .iter()
        .map(|item| item.as_str().unwrap().to_string())
        .collect()
}

#[test]
fn the_content_security_policy_is_exactly_the_plans() {
    let config = json("tauri.conf.json");
    assert_eq!(config["app"]["security"]["csp"], CSP);
    let security = config["app"]["security"].as_object().unwrap();
    assert_eq!(
        security.keys().collect::<Vec<_>>(),
        ["csp"],
        "nothing else loosens the policy"
    );
}

#[test]
fn the_main_window_may_listen_and_call_its_ten_commands_and_nothing_else() {
    let capability = json("capabilities/main-window.json");
    assert_eq!(strings(&capability["windows"]), ["main".to_string()].into());
    let expected: BTreeSet<String> = MAIN_WINDOW_COMMANDS
        .iter()
        .map(|command| permission(command))
        .chain([
            "core:event:allow-listen".to_string(),
            "core:event:allow-unlisten".to_string(),
        ])
        .collect();
    assert_eq!(strings(&capability["permissions"]), expected);
}

#[test]
fn the_confirmation_window_may_read_its_question_and_answer_it_and_nothing_else() {
    let capability = json("capabilities/confirmation-window.json");
    assert_eq!(
        strings(&capability["windows"]),
        ["confirmation".to_string()].into()
    );
    let expected: BTreeSet<String> = CONFIRMATION_COMMANDS
        .iter()
        .map(|command| permission(command))
        .collect();
    assert_eq!(strings(&capability["permissions"]), expected);
}

#[test]
fn no_other_capability_exists_and_none_is_inline_or_remote() {
    let mut found: Vec<String> = std::fs::read_dir(app_file("capabilities"))
        .unwrap()
        .map(|entry| entry.unwrap().file_name().into_string().unwrap())
        .collect();
    found.sort();
    assert_eq!(found, ["confirmation-window.json", "main-window.json"]);
    let config = json("tauri.conf.json");
    assert!(config["app"]["security"].get("capabilities").is_none());
    for file in &found {
        let capability = json(&format!("capabilities/{file}"));
        assert!(capability.get("remote").is_none(), "{file}");
        assert!(capability.get("webviews").is_none(), "{file}");
    }
}

#[test]
fn every_command_has_its_permission_file_checked_in_and_no_other_file_is_there() {
    let source = std::fs::read_to_string(app_file("build.rs")).unwrap();
    let list = source
        .split("const COMMANDS")
        .nth(1)
        .unwrap()
        .split(';')
        .nth(1)
        .unwrap();
    let declared: BTreeSet<String> = list
        .split('"')
        .skip(1)
        .step_by(2)
        .map(str::to_string)
        .collect();
    let expected: BTreeSet<String> = MAIN_WINDOW_COMMANDS
        .iter()
        .chain(&CONFIRMATION_COMMANDS)
        .map(|command| (*command).to_string())
        .collect();
    assert_eq!(
        declared, expected,
        "build.rs declares the commands of the two windows"
    );

    let directory = app_file("permissions/autogenerated");
    let files: BTreeSet<String> = std::fs::read_dir(&directory)
        .unwrap()
        .map(|entry| entry.unwrap().file_name().into_string().unwrap())
        .collect();
    let wanted: BTreeSet<String> = expected
        .iter()
        .map(|command| format!("{command}.toml"))
        .collect();
    assert_eq!(files, wanted);
    for command in &expected {
        let text = std::fs::read_to_string(directory.join(format!("{command}.toml"))).unwrap();
        assert!(
            text.contains(&format!("identifier = \"{}\"", permission(command))),
            "{command}"
        );
        assert!(
            text.contains(&format!("commands.allow = [\"{command}\"]")),
            "{command}"
        );
    }
}

#[test]
fn the_main_window_opens_at_880_by_680_with_a_minimum_width_of_480() {
    let config = json("tauri.conf.json");
    let windows = config["app"]["windows"].as_array().unwrap();
    assert_eq!(
        windows.len(),
        1,
        "the confirmation window is made when it is needed"
    );
    let main = &windows[0];
    assert_eq!(main["label"], "main");
    assert_eq!(main["width"], 880);
    assert_eq!(main["height"], 680);
    assert_eq!(main["minWidth"], 480);
    assert_eq!(config["identifier"], "app.axross.marshal");
    assert_eq!(config["app"]["withGlobalTauri"], true);
}

#[test]
fn the_opener_plugins_page_script_is_off_and_no_capability_names_it() {
    let source = std::fs::read_to_string(app_file("src/app.rs")).unwrap();
    assert!(
        source.contains(
            "tauri_plugin_opener::Builder::new()\n        .open_js_links_on_click(false)"
        ),
        "the app builds the opener plugin with its page script off"
    );
    assert!(!source.contains("tauri_plugin_opener::init"));
    assert!(!source.contains("tauri_plugin_opener::Builder::default"));
    assert_eq!(
        source.matches("tauri_plugin_opener::").count(),
        1,
        "the opener is built in one place"
    );
    assert!(
        source.contains(".plugin(opener())"),
        "and registered from it"
    );
    for file in ["main-window.json", "confirmation-window.json"] {
        let capability = json(&format!("capabilities/{file}"));
        assert!(
            strings(&capability["permissions"])
                .iter()
                .all(|permission| !permission.starts_with("opener:")),
            "{file} grants none of the opener plugin's commands"
        );
    }
}
